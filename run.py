def menu() -> None:
    from src.brand import terminal_logo
    from src.sequence import hyperlink

    color = "NO_COLOR" not in os.environ
    if os.name == "nt":
        os.system("")  # ANSI escape codes in the Windows console
    with warehouse_lock(), contextlib.redirect_stdout(io.StringIO()):
        cmd_reset_data(argparse.Namespace())  # every session starts clean, so option 1 runs the whole sequence
    url, dashboard = start_dashboard()
    log = WAREHOUSE_DIR / "sequence.log"
    try:
        while True:
            print("\x1b[2J\x1b[3J\x1b[H", end="")  # a clean screen every time the menu shows
            files = files_loaded()
            first_run = files == 0
            mode = ("first run: ingests data/landing and builds everything, about 3 minutes" if first_run
                    else "incremental: only new or changed files in data/landing")
            print(terminal_logo(color))
            print("  P A G O  ·  remittances analytics · dbt + DuckDB + MetricFlow\n")
            print(f"  Dashboard  {hyperlink(url, enabled=color)}   running in the background, click to open")
            print(f"  Warehouse  {'not built yet' if first_run else f'{files} landing files loaded'}"
                  + (f"   last run log: {hyperlink(log.resolve().as_uri(), 'warehouse/sequence.log', color)}"
                     if log.exists() else ""))
            print("  " + "─" * 76)
            print("  1  Run sequentially   ingest → staging → intermediate → snapshots → core → marts → metrics")
            print(f"                        {mode}")
            print("  2  Add a monthly test batch and run it sequentially")
            print("  3  Run the checks (dbt test, pytest, ruff, sqlfluff)")
            print("  4  Open the dashboard in the browser")
            print("  5  Reset to the original data (deletes the warehouse)")
            print("  0  Exit (stops the dashboard)")
            try:
                choice = input("\n  Choose an option [1]: ").strip() or "1"
            except (EOFError, KeyboardInterrupt):
                print()
                return
            if choice == "0":
                return
            if choice in ("1", "2", "3", "5"):
                print("\x1b[2J\x1b[3J\x1b[H", end="")
            if choice == "1":
                menu_action(cmd_pipeline, url, color)
            elif choice == "2":
                menu_add_batch(first_run, url, color)
            elif choice == "3":
                menu_action(cmd_checks, url, color)
            elif choice == "4":
                webbrowser.open(url)
            elif choice == "5" and input("  Delete the warehouse and restore data/landing to the baseline? [y/N]: ").strip().lower() == "y":
                menu_action(cmd_reset_data, url, color)
    finally:
        stop_dashboard(dashboard)


