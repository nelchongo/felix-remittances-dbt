def dashboard_up(port: int) -> bool:
    try:
        with urllib.request.urlopen(f"http://localhost:{port}/_stcore/health", timeout=1) as response:
            return response.status == 200
    except OSError:
        return False


def start_dashboard() -> tuple[str, subprocess.Popen | None]:
    """Serve the dashboard in the background on the first free port from 8501; output goes to
    warehouse/dashboard.log. It reads DuckDB read-only, so dbt keeps working while it runs."""
    port = next((p for p in range(DASHBOARD_PORT, DASHBOARD_PORT + 20) if port_is_free(p)), None)
    if port is None:
        print(f"No free port for the dashboard between {DASHBOARD_PORT} and {DASHBOARD_PORT + 19}.")
        return "(not running)", None
    WAREHOUSE_DIR.mkdir(exist_ok=True)
    detach = ({"creationflags": subprocess.CREATE_NEW_PROCESS_GROUP} if os.name == "nt"
              else {"start_new_session": True})  # Ctrl+C during a dbt run must not stop the dashboard
    with (WAREHOUSE_DIR / "dashboard.log").open("w", encoding="utf-8") as log:
        command = dashboard_command("--server.headless", "true", "--server.port", str(port))
        process = subprocess.Popen([find_tool(command[0]), *command[1:]], cwd=ROOT, env=tool_env(),
                                   stdout=log, stderr=subprocess.STDOUT, **detach)
    url = f"http://localhost:{port}"
    for _ in range(60):
        if dashboard_up(port):
            return url, process
        if process.poll() is not None:
            break
        time.sleep(0.5)
    print("The dashboard did not start; see warehouse/dashboard.log.")
    return url, process


def port_is_free(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        return sock.connect_ex(("127.0.0.1", port)) != 0


def stop_dashboard(process: subprocess.Popen | None) -> None:
    if process is not None and process.poll() is None:
        process.terminate()
        try:
            process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            process.kill()


