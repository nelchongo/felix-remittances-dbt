def tool_env() -> dict[str, str]:
    """Environment for every child process (dbt, mf, streamlit, ...)."""
    env = os.environ.copy()
    env["DBT_PROJECT_DIR"] = str(DBT_DIR)
    env["DBT_PROFILES_DIR"] = str(DBT_DIR)
    env["DO_NOT_TRACK"] = "1"
    env["PYTHONIOENCODING"] = "utf-8"  # mf prints emoji; keeps Windows consoles happy
    env.setdefault("DUCKDB_PATH", str(DEFAULT_DB_PATH))
    return env


def find_tool(name: str) -> str:
    """Resolve a console script, preferring the one installed next to this interpreter."""
    scripts_dir = Path(sys.executable).parent
    found = shutil.which(name, path=str(scripts_dir)) or shutil.which(name)
    if not found:
        sys.exit(
            f"error: '{name}' was not found. Activate the virtualenv and run "
            "`pip install -r requirements.txt` first."
        )
    return found


def run(cmd: list[str], cwd: Path = DBT_DIR) -> None:
    """Run a tool and stop the whole command on the first failure."""
    WAREHOUSE_DIR.mkdir(exist_ok=True)
    print(f"\n$ {' '.join(cmd)}", flush=True)
    result = subprocess.run([find_tool(cmd[0]), *cmd[1:]], cwd=cwd, env=tool_env(), stdout=current_stdout(),
                            stderr=subprocess.STDOUT, check=False)
    if result.returncode != 0:
        sys.exit(result.returncode)


@contextlib.contextmanager
def warehouse_lock():
    """One run.py at a time writes the warehouse (DuckDB allows a single writer). A second one stops with a clear
    message instead of a lock error halfway through; a lock left by a process that no longer exists is taken over."""
    lock = WAREHOUSE_DIR / ".run.lock"
    WAREHOUSE_DIR.mkdir(exist_ok=True)
    if lock.exists():
        pid = lock.read_text().strip()
        if pid.isdigit() and int(pid) != os.getpid() and process_alive(int(pid)):
            sys.exit(f"error: another run.py (PID {pid}) is using the warehouse. Wait for it to finish, then try again.")
    lock.write_text(str(os.getpid()))
    try:
        yield
    finally:
        with contextlib.suppress(FileNotFoundError):
            if lock.read_text().strip() == str(os.getpid()):
                lock.unlink()


def process_alive(pid: int) -> bool:
    if os.name == "nt":  # no signal 0 on Windows: trust locks written in the last 2 hours
        return time.time() - (WAREHOUSE_DIR / ".run.lock").stat().st_mtime < 7200
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


def current_stdout():
    """sys.stdout when it is a real file (the step log while the sequence draws its progress), else inherit."""
    try:
        sys.stdout.flush()
        sys.stdout.fileno()
    except (AttributeError, OSError, ValueError):
        return None
    return sys.stdout


