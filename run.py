def files_loaded() -> int:
    """Landing files in raw._ingestion_log (0 before the first load). Read-only, so it never blocks the dashboard."""
    import duckdb

    if not db_path().exists():
        return 0
    try:
        with duckdb.connect(str(db_path()), read_only=True) as con:
            return con.execute("select count(*) from raw._ingestion_log").fetchone()[0]
    except duckdb.Error:
        return 0


def cmd_pipeline(_: argparse.Namespace) -> None:
    """The dbt sequence, step by step: a first run when nothing is ingested yet, incremental afterwards."""
    run_sequence(first_run=files_loaded() == 0)


