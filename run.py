def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="run.py",
        description="Félix remittances: dbt + DuckDB + MetricFlow pipeline runner.",
    )
    sub = parser.add_subparsers(dest="command", required=True, metavar="<command>")
    for name, help_text, func in COMMANDS:
        p = sub.add_parser(name, help=help_text, description=help_text)
        if name == "add-batch":
            p.add_argument("batch", help="folder name under data/test_batches/ (e.g. 2026-07, edge_cases)")
        if name == "build":
            p.add_argument("--full-refresh", action="store_true", help="rebuild the incremental facts from scratch")
        p.set_defaults(func=func)
    return parser


def main(argv: list[str] | None = None) -> None:
    argv = sys.argv[1:] if argv is None else argv
    if not argv:  # no command: the menu when a person is at the terminal, the help otherwise (CI, pipes)
        if sys.stdin.isatty():
            menu()
        else:
            build_parser().print_help()
        return
    args = build_parser().parse_args(argv)
    try:
        if args.command == "dashboard":  # only reads the warehouse
            args.func(args)
        else:
            with warehouse_lock():
                args.func(args)
    except KeyboardInterrupt:
        sys.exit(130)


if __name__ == "__main__":
    main()
