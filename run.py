def menu_action(func, url: str, color: bool) -> None:
    """Run a command from the menu: a failure or Ctrl+C returns to the menu instead of closing it."""
    from src.sequence import hyperlink

    try:
        with warehouse_lock():
            func(argparse.Namespace())
        print(f"\n  Dashboard: {hyperlink(url, enabled=color)}  (refresh the page to see the result)")
    except SystemExit as exc:
        if exc.code not in (0, None):
            print(f"\n  ✗ {exc.code}" if isinstance(exc.code, str) else f"\n  ✗ Stopped with exit code {exc.code} (see above).")
    except KeyboardInterrupt:
        print("\n  ✗ Interrupted.")
    except Exception as exc:  # noqa: BLE001 (the menu reports anything unexpected and stays open)
        print(f"\n  ✗ Stopped by an unexpected error: {type(exc).__name__}: {exc}")
    with contextlib.suppress(EOFError, KeyboardInterrupt):
        input("\n  Press Enter to go back to the menu ")


def menu_add_batch(first_run: bool, url: str, color: bool) -> None:
    batches = sorted(p.name for p in TEST_BATCHES_DIR.iterdir() if p.is_dir())
    for number, batch in enumerate(batches, 1):
        loaded = " (already in data/landing)" if any(LANDING_DIR.glob(f"*/*__{batch}.csv")) else ""
        note = " (bad rows on purpose: the build stops at the data tests)" if batch == "edge_cases" else ""
        print(f"  {number}  {batch}{loaded}{note}")
    pick = input("Batch number (Enter to go back): ").strip()
    if not pick.isdigit() or not 1 <= int(pick) <= len(batches):
        return
    batch = batches[int(pick) - 1]

    def add(args: argparse.Namespace) -> None:
        if first_run:  # ingest the baseline first, so the batch really is an increment
            cmd_pipeline(args)
        copy_batch(batch)
        cmd_pipeline(args)

    menu_action(add, url, color)


